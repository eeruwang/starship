// Map for notification types
export function getNotifIcon(type, reaction) {
  switch (type) {
    case 'reaction': {
      // Replace common unicode reactions with styled SVG icons
      if (!reaction || reaction === '❤' || reaction === '❤️') return iconHeartFill;
      if (reaction === '⭐' || reaction === '⭐️') return iconStarFill;
      return reaction;
    }
    case 'reply': return iconReplyNotif;
    case 'renote': case 'reblog': return iconBoostNotif;
    case 'quote': return iconReplyNotif;
    case 'mention': return iconMegaphone;
    case 'follow': return iconUserFollow;
    case 'followRequestAccepted': return iconCheck;
    case 'receiveFollowRequest': case 'follow_request': return iconBell;
    case 'pollEnded': case 'poll': return iconPoll;
    case 'achievementEarned': return iconTrophy;
    case 'app': return iconApp;
    case 'note': case 'status': return iconNote;
    case 'favourite': return iconHeartFill;
    case 'update': return iconPencil;
    default: return iconBell;
  }
}
